#!/usr/bin/env node
// Render deploy-time files from `terraform output -json`:
//   apps/control/dist/config.js, apps/admin/dist/config.js  (public runtime config; no secrets)
//   .firebaserc                                              (project + hosting targets)
//   firebase.deploy.json                                     (firebase.json with the Cloud Run region/service patched in)
// Usage: node scripts/render-deploy-config.mjs --outputs tf-outputs.json [--version 1.0.0] [--check]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const outputsPath = opt('--outputs');
if (!outputsPath) { console.error('usage: render-deploy-config.mjs --outputs <terraform output -json file>'); process.exit(2); }

const raw = JSON.parse(readFileSync(outputsPath, 'utf8'));
const out = Object.fromEntries(Object.entries(raw).map(([k, v]) => [k, v.value]));
const need = ['project_id', 'region', 'api_service', 'hosting_site_control', 'hosting_site_admin', 'auth_domain_control', 'auth_domain_admin', 'firebase_config'];
for (const k of need) if (out[k] == null) { console.error(`terraform output missing: ${k}`); process.exit(1); }
const fb = out.firebase_config;
for (const k of ['apiKey', 'projectId', 'appId']) if (!fb[k]) { console.error(`firebase_config.${k} is empty`); process.exit(1); }

const version = opt('--version', JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version);

const sites = [
  { app: 'control', site: out.hosting_site_control, authDomain: out.auth_domain_control },
  { app: 'admin', site: out.hosting_site_admin, authDomain: out.auth_domain_admin },
];

for (const s of sites) {
  const dist = join(root, 'apps', s.app, 'dist');
  if (!existsSync(dist)) mkdirSync(dist, { recursive: true });
  const cfg = {
    authMode: 'firebase',
    apiBase: '/api',
    version,
    firebase: { apiKey: fb.apiKey, authDomain: s.authDomain, projectId: fb.projectId, appId: fb.appId },
  };
  writeFileSync(join(dist, 'config.js'), `// Generated by scripts/render-deploy-config.mjs from Terraform outputs. Public values only; no secrets.\nwindow.__CONFIG__ = ${JSON.stringify(cfg, null, 2)};\n`);
  console.log(`wrote apps/${s.app}/dist/config.js (authDomain ${s.authDomain})`);
}

writeFileSync(join(root, '.firebaserc'), JSON.stringify({
  projects: { default: out.project_id },
  targets: { [out.project_id]: { hosting: { control: [out.hosting_site_control], admin: [out.hosting_site_admin] } } },
}, null, 2) + '\n');
console.log('wrote .firebaserc');

const fj = JSON.parse(readFileSync(join(root, 'firebase.json'), 'utf8'));
for (const h of fj.hosting) for (const r of h.rewrites ?? []) if (r.run) { r.run.region = out.region; r.run.serviceId = out.api_service; }
writeFileSync(join(root, 'firebase.deploy.json'), JSON.stringify(fj, null, 2) + '\n');
console.log(`wrote firebase.deploy.json (Cloud Run ${out.api_service} in ${out.region})`);
